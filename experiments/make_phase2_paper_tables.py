"""Paper tables, figures and macros for H3 / H4, generated from the COMBINED artifacts only.

    python -m experiments.make_phase2_tables          # first: rebuild <root>/combined/
    python -m experiments.make_phase2_paper_tables    # then:  writing/generated/

Writes (every value read from <output-root>/combined/*.csv -- nothing is typed by hand):

    h3_ladder_table.tex      Table H3-1: the compatibility ladder at the frozen Phase-1 entrance
    h3_depth_curves.pdf      Figure H3-1: representative datasets x models, test MASE / native over
                             depth for the hard cut, NOA, FL and the probe (native = 1)
    h3_ladder_at_entrance.pdf  the ladder at the entrance, every dataset, per model
    h4_truncation_table.tex  Table H4-1: physically truncated models at the entrance, measured
                             speedup / throughput / memory / active parameters
    h4_outcome_table.tex     Table H4-2: the pre-registered verdict per model (success / failure
                             (fragile) / entrance = final block); failures are counted, not hidden
    phase2_macros.tex        \\newcommand macros for numbers the prose quotes

A table with no data yet is written as an explicit placeholder that fails LaTeX loudly, so a draft
can never silently compile against missing results. The same happens to BOTH H4 tables while any
H4 cell is invalid (its physical model failed V3): such a cell is a pipeline error to fix.
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from probing import phase1, phase2, registry                                      # noqa: E402

GEN = REPO_ROOT / "writing" / "generated"
REPRESENTATIVE = ("monash_electricity_hourly", "uber_tlc_hourly", "monash_london_smart_meters")
RUNGS = [("hard", "Hard cut"), ("noa", "Label-free alignment"), ("fl", "Supervised alignment"),
         ("probe", "Phase-1 probe")]
COLORS = {"hard": "#9E9E9E", "noa": "#1B7837", "fl": "#5E3C99", "probe": "#E08A00"}
MODEL_NAMES = {m: phase1.model_spec(m).display_name for m in phase1.MODELS}


def _rows(p: Path):
    if not p.exists():
        return []
    with open(p) as fh:
        return list(csv.DictReader(fh))


def _f(x):
    try:
        v = float(x)
        return v if np.isfinite(v) else None
    except (TypeError, ValueError):
        return None


def _pct(x):
    return "--" if x is None else f"{100 * x:+.1f}\\%"


def _missing(path: Path, what: str,
             why: str = "NO DATA YET -- run the Phase-2 jobs, then make_phase2_tables"):
    path.write_text(f"% {what}: {why}\n\\PhaseTwoMissing{{{what}}}\n")


# --------------------------------------------------------------------------- #
def ladder_table(summary, out: Path):
    rows = [r for r in summary if r["includes_low_skill"] == "True"]
    if not rows:
        return _missing(out, "h3_ladder_table")
    lines = ["% generated by experiments.make_phase2_paper_tables -- do not edit",
             "% n = datasets whose Phase-1 entrance lies BEFORE the final block; a dataset whose "
             "entrance IS the final block has no intermediate state to test and is counted in the "
             "last column instead",
             "\\begin{tabular}{llrrrrrr}", "\\toprule",
             "Model & Rung & $n$ & $\\Delta$MASE median [IQR] & $\\Delta$WQL median & "
             "within 5\\% & gap closure & entrance = final \\\\", "\\midrule"]
    for m in phase1.MODELS:
        for key, name in RUNGS:
            r = next((x for x in rows if x["model"] == m and x["rung"] == key), None)
            if r is None:
                continue
            q = [_f(r["mase_degradation_q25"]), _f(r["mase_degradation_median"]),
                 _f(r["mase_degradation_q75"])]
            lines.append(f"{MODEL_NAMES[m]} & {name} & {r['n_datasets']} & "
                         f"{_pct(q[1])} [{_pct(q[0])}, {_pct(q[2])}] & "
                         f"{_pct(_f(r['wql_degradation_median']))} & "
                         f"{r['n_within_5pct_mase']}/{r['n_datasets']} & "
                         f"{'--' if _f(r['gap_closure_median']) is None else '%.2f' % _f(r['gap_closure_median'])} & "
                         f"{r['n_entrance_is_final_block']} \\\\")
        if lines[-1] != "\\midrule":          # a model with no rows adds no rule
            lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines.append("\\end{tabular}")
    out.write_text("\n".join(lines) + "\n")


def truncation_table(joined, out: Path):
    if not joined:
        return _missing(out, "h4_truncation_table")
    arms = [("hard", "Hard-cut truncation"), ("noa", "Label-free aligned truncation"),
            ("fl", "Supervised aligned truncation"), ("probe_head", "Probe-head truncation"),
            ("chronos2_small", "Chronos-2-small")]
    lines = ["% generated by experiments.make_phase2_paper_tables -- do not edit",
             "% truncation rows aggregate the datasets whose Phase-1 entrance lies BEFORE the "
             "final block (a truncated model exists); Chronos-2-small: every dataset",
             "\\begin{tabular}{llrrrrrr}", "\\toprule",
             "Model & Model variant & blocks removed & params removed & speedup B=1 & "
             "speedup B=256 & $\\Delta$MASE median & within 5\\% \\\\", "\\midrule"]
    for m in phase1.MODELS:
        for key, name in arms:
            rr = [r for r in joined if r["model"] == m and r["arm"] == key]
            if key != "chronos2_small":
                rr = [r for r in rr if (_f(r["blocks_removed"]) or 0) > 0]
            if not rr:
                continue
            med = lambda k: (float(np.median([_f(r[k]) for r in rr if _f(r[k]) is not None]))  # noqa
                             if any(_f(r[k]) is not None for r in rr) else None)
            s1, s256 = med("api_e2e_B1_speedup"), med("api_e2e_B256_speedup")
            x = "$\\times$"                       # no backslash inside an f-string expression
            sp1 = "--" if s1 is None else f"{s1:.2f}{x}"
            sp256 = "--" if s256 is None else f"{s256:.2f}{x}"
            mr = med("mase_ratio")
            nwin = sum(r["within_budget_mase"] == "True" for r in rr)
            lines.append(
                f"{MODEL_NAMES[m]} & {name} & {med('blocks_removed') or 0:.0f} & "
                f"{_pct(med('fraction_params_removed'))} & {sp1} & {sp256} & "
                f"{_pct(None if mr is None else mr - 1)} & {nwin}/{len(rr)} " + "\\\\")
        if lines[-1] != "\\midrule":          # a model with no rows adds no rule
            lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines.append("\\end{tabular}")
    out.write_text("\n".join(lines) + "\n")


def outcome_table(outcome_summary, out: Path):
    """Table H4-2: the pre-registered verdict at the frozen Phase-1 entrance, per model. Failures
    are counted, never hidden; a cell that could not be truncated is its own column."""
    rows = [r for r in outcome_summary if r["includes_low_skill"] == "True"]
    if not rows:
        return _missing(out, "h4_outcome_table")
    lines = ["% generated by experiments.make_phase2_paper_tables -- do not edit",
             "% rule (probing.phase2.H4_OUTCOME_RULE): candidate depth = the frozen Phase-1 5% "
             "entrance; success = label-free aligned truncation dMASE <= 5%; a failure is "
             "reported, never replaced by another depth",
             "\\begin{tabular}{lrrrrr}", "\\toprule",
             "Model & datasets & truncatable & success & failure (fragile) & "
             "entrance = final \\\\", "\\midrule"]
    for m in phase1.MODELS:
        r = next((x for x in rows if x["model"] == m), None)
        if r is None:
            continue
        lines.append(f"{MODEL_NAMES[m]} & {r['n_datasets']} & {r['n_truncatable']} & "
                     f"{r['n_success']} & {r['n_failure']} ({r['n_failure_fragile']}) & "
                     f"{r['n_no_truncation_possible']} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    out.write_text("\n".join(lines) + "\n")


def depth_curves(depth_rows, ladder, out: Path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    if not depth_rows:
        return _missing(out.with_suffix(".tex"), "h3_depth_curves")
    fig, axes = plt.subplots(len(REPRESENTATIVE), 3, figsize=(7.0, 6.2), squeeze=False,
                             layout="constrained")
    for i, tag in enumerate(REPRESENTATIVE):
        for j, m in enumerate(phase1.MODELS):
            ax = axes[i][j]
            rr = [r for r in depth_rows if r["model"] == m and r["dataset"] == tag]
            ax.axhline(1.0, color="black", lw=0.8, label="native")
            for key, name in RUNGS:
                pts = sorted((float(r["relative_depth"]), _f(r["mase_ratio_vs_native"]))
                             for r in rr if r["family"] == key and _f(r["mase_ratio_vs_native"]))
                if pts:
                    ax.plot(*zip(*pts), color=COLORS[key], lw=1.2, marker=".", ms=3, label=name)
            ent = next((_f(r["relative_depth"]) for r in ladder if r["model"] == m and
                        r["dataset"] == tag and r["is_headline"] == "True"), None)
            if ent is not None:
                ax.axvline(ent, color="#1B7837", ls="--", lw=0.8)
            ax.set_yscale("log")
            if i == 0:
                ax.set_title(MODEL_NAMES[m], fontsize=9)
            if j == 0:
                ax.set_ylabel(f"{registry.display_name(tag)}\ntest MASE / native", fontsize=8)
            if i == len(REPRESENTATIVE) - 1:
                ax.set_xlabel("normalized depth", fontsize=8)
            ax.tick_params(labelsize=7)
    h, l = axes[0][0].get_legend_handles_labels()
    fig.legend(h, l, loc="lower center", ncol=5, fontsize=7, bbox_to_anchor=(0.5, -0.04))
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)


def ladder_figure(ladder, out: Path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    head = [r for r in ladder if r["is_headline"] == "True"]
    if not head:
        return _missing(out.with_suffix(".tex"), "h3_ladder_at_entrance")
    fig, axes = plt.subplots(1, 3, figsize=(7.0, 2.4), layout="constrained")
    for ax, m in zip(axes, phase1.MODELS):
        rungs = [k for k, _ in RUNGS if any(r["model"] == m and r["rung"] == k for r in head)]
        for tag in sorted({r["dataset"] for r in head if r["model"] == m}):
            ys = [next((_f(r["mase_ratio"]) for r in head if r["model"] == m and
                        r["dataset"] == tag and r["rung"] == k), np.nan) for k in rungs]
            ax.plot(range(len(rungs)), ys, color="#BBBBBB", lw=0.7,
                    alpha=0.6 if (tag not in REPRESENTATIVE) else 1.0)
        med = [np.nanmedian([_f(r["mase_ratio"]) for r in head if r["model"] == m
                             and r["rung"] == k]) for k in rungs]
        ax.plot(range(len(rungs)), med, color="black", lw=2, marker="o", ms=4)
        ax.axhline(1.0, color="black", lw=0.6)
        ax.axhspan(1.0, 1.0 + phase2.BUDGET, color="#1B7837", alpha=0.12)
        ax.set_xticks(range(len(rungs)))
        ax.set_xticklabels([dict(RUNGS)[k].replace(" alignment", "\nalign.") for k in rungs],
                           fontsize=6)
        ax.set_yscale("log")
        ax.set_title(MODEL_NAMES[m], fontsize=9)
    axes[0].set_ylabel("test MASE / native\n(at the Phase-1 entrance)", fontsize=8)
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)


def macros(summary, outcome_summary, out: Path):
    lines = ["% generated by experiments.make_phase2_paper_tables -- do not edit",
             "\\providecommand{\\PhaseTwoMissing}[1]{\\errmessage{Phase-2 artifact missing: #1}}"]
    for r in summary:
        if r["includes_low_skill"] != "True":
            continue
        name = f"phtwo{r['model']}{r['rung']}".replace("chronos2", "chronos").replace(
            "timesfm3", "timesfm").replace("_", "")
        med = _f(r["mase_degradation_median"])
        lines.append(f"\\newcommand{{\\{name}MaseMedian}}{{{_pct(med)}}}")
        lines.append(f"\\newcommand{{\\{name}WithinFive}}{{{r['n_within_5pct_mase']}/"
                     f"{r['n_datasets']}}}")
    for r in outcome_summary:
        if r["includes_low_skill"] != "True":
            continue
        base = f"phtwo{r['model']}".replace("chronos2", "chronos").replace("timesfm3", "timesfm")
        lines.append(f"\\newcommand{{\\{base}HfourSuccess}}{{{r['n_success']}/{r['n_truncatable']}}}")
        lines.append(f"\\newcommand{{\\{base}HfourFailure}}{{{r['n_failure']}/{r['n_truncatable']}}}")
        lines.append(f"\\newcommand{{\\{base}HfourNoTruncation}}{{{r['n_no_truncation_possible']}}}")
    out.write_text("\n".join(lines) + "\n")


def build(output_root, gen_dir=GEN) -> dict:
    comb = Path(output_root) / "combined"
    gen = Path(gen_dir)
    gen.mkdir(parents=True, exist_ok=True)
    summary = _rows(comb / "h3_summary_by_model.csv")
    ladder = _rows(comb / "h3_ladder.csv")
    depth_rows = _rows(comb / "h3_depth_metrics.csv")
    joined = _rows(comb / "h4_with_latency.csv")
    outcomes = _rows(comb / "h4_outcome_summary.csv")
    ladder_table(summary, gen / "h3_ladder_table.tex")
    invalid = [f"{r['model']}: {r['invalid_datasets']}" for r in outcomes
               if r["includes_low_skill"] == "True" and int(r["n_invalid_v3"]) > 0]
    if invalid:
        why = ("invalid H4 cells (physical model failed V3) " + "; ".join(invalid)).replace("_", "-")
        fix = "INVALID H4 CELLS -- fix V3 and re-run evaluate before any H4 table is built"
        _missing(gen / "h4_truncation_table.tex", "h4_truncation_table: " + why, fix)
        _missing(gen / "h4_outcome_table.tex", "h4_outcome_table: " + why, fix)
    else:
        truncation_table(joined, gen / "h4_truncation_table.tex")
        outcome_table(outcomes, gen / "h4_outcome_table.tex")
    depth_curves(depth_rows, ladder, gen / "h3_depth_curves.pdf")
    ladder_figure(ladder, gen / "h3_ladder_at_entrance.pdf")
    macros(summary, outcomes, gen / "phase2_macros.tex")
    return {"out": str(gen), "files": sorted(p.name for p in gen.iterdir())}


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--output-root", default=str(phase2.DEFAULT_OUT_ROOT))
    p.add_argument("--generated-dir", default=str(GEN))
    a = p.parse_args(argv)
    print(f"[phase2 paper tables] {build(a.output_root, a.generated_dir)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
